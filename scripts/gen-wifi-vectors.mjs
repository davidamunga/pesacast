// Generates docs/wifi-crypto-vectors.json: known-answer vectors for the WiFi v2 secure channel
// (docs/protocol.md). Uses only node:crypto so it is independent of both the Kotlin and the
// TypeScript implementations, which must reproduce these values exactly in their unit tests.
import { createECDH, hkdfSync, createCipheriv } from "node:crypto";
import { writeFileSync } from "node:fs";
import { resolve, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const hex = (b) => Buffer.from(b).toString("hex");

// Fixed scalars (valid P-256 private keys) and nonces; test data only.
const clientD = Buffer.alloc(32, 0x11);
const serverD = Buffer.alloc(32, 0x22);
const clientNonce = Buffer.from("000102030405060708090a0b0c0d0e0f", "hex");
const serverNonce = Buffer.from("f0f1f2f3f4f5f6f7f8f9fafbfcfdfeff", "hex");
const token = "test-pairing-token-not-a-secret-0123456789ab";

const c = createECDH("prime256v1");
c.setPrivateKey(clientD);
const s = createECDH("prime256v1");
s.setPrivateKey(serverD);
const clientPub = c.getPublicKey(); // 65-byte uncompressed point
const serverPub = s.getPublicKey();
const shared = c.computeSecret(serverPub);
if (!shared.equals(s.computeSecret(clientPub))) throw new Error("ECDH mismatch");

const info = Buffer.concat([Buffer.from("pesacast-v2"), clientPub, serverPub, clientNonce, serverNonce]);
const okm = Buffer.from(hkdfSync("sha256", shared, Buffer.from(token, "utf8"), info, 64));
const keyC2S = okm.subarray(0, 32);
const keyS2C = okm.subarray(32, 64);

function seal(key, direction, counter, plaintext) {
  const ctr = Buffer.alloc(8);
  ctr.writeBigUInt64BE(BigInt(counter));
  const nonce = Buffer.concat([Buffer.alloc(4), ctr]);
  const aad = Buffer.concat([Buffer.from([direction]), ctr]);
  const cipher = createCipheriv("aes-256-gcm", key, nonce);
  cipher.setAAD(aad);
  const ct = Buffer.concat([cipher.update(plaintext, "utf8"), cipher.final(), cipher.getAuthTag()]);
  return Buffer.concat([ctr, ct]); // record = counter(8) || ciphertext || tag(16)
}

const vectors = {
  description: "Known-answer vectors for the PesaCast WiFi v2 secure channel. Generated by scripts/gen-wifi-vectors.mjs; do not edit by hand.",
  token,
  clientPrivateKey: hex(clientD),
  serverPrivateKey: hex(serverD),
  clientPublicKey: hex(clientPub),
  serverPublicKey: hex(serverPub),
  clientNonce: hex(clientNonce),
  serverNonce: hex(serverNonce),
  sharedSecret: hex(shared),
  keyClientToServer: hex(keyC2S),
  keyServerToClient: hex(keyS2C),
  records: [
    { direction: "client-to-server", counter: 0, plaintext: '{"ready":true}', record: hex(seal(keyC2S, 1, 0, '{"ready":true}')) },
    { direction: "server-to-client", counter: 0, plaintext: '{"status":"ok"}', record: hex(seal(keyS2C, 2, 0, '{"status":"ok"}')) },
    { direction: "server-to-client", counter: 1, plaintext: '{"type":"mpesa_txn","amount":500}', record: hex(seal(keyS2C, 2, 1, '{"type":"mpesa_txn","amount":500}')) },
  ],
};

writeFileSync(resolve(root, "docs/wifi-crypto-vectors.json"), JSON.stringify(vectors, null, 2) + "\n");
console.log("wrote docs/wifi-crypto-vectors.json");
